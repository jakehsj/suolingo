"""Synthetic recordings for tests.

These are generated numbers, NOT real tracking data or sign-language content.
Regenerate the committed fixture with:

    uv run python -m tests.factory
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from app.schemas.recording import FINGER_NAMES, JOINT_NAMES, SCHEMA_ID, SCHEMA_VERSION

FIXTURE_PATH = (
    Path(__file__).resolve().parents[3] / "tests" / "fixtures" / "recordings" / "synthetic-interruption.json"
)


def hand(tracked: bool, t: float, offset_x: float, sample_time: float | None) -> dict:
    sample = {
        "tracked": tracked,
        "high_confidence": tracked,
        "input_state_valid": tracked,
        "system_gesture": False,
        "sample_time": sample_time,
        "hand_scale": 1.0 if tracked else None,
        "finger_high_confidence": [tracked] * len(FINGER_NAMES),
        "pinch_strength": [0.0] * len(FINGER_NAMES),
        "root": None,
        "joint_positions": None,
        "joint_rotations": None,
    }
    if tracked:
        wave = 0.05 * math.sin(2 * math.pi * t)
        sample["root"] = {"position": [offset_x, 1.2 + wave, 0.35], "rotation": [0.0, 0.0, 0.0, 1.0]}
        sample["joint_positions"] = [
            [round(offset_x + 0.004 * i, 5), round(1.2 + wave + 0.002 * i, 5), 0.35]
            for i in range(len(JOINT_NAMES))
        ]
        sample["joint_rotations"] = [[0.0, 0.0, 0.0, 1.0] for _ in JOINT_NAMES]
    return sample


def make_recording(
    frame_count: int = 40,
    rate_hz: float = 72.0,
    left_lost: range | None = range(12, 20),
    right_lost: range | None = None,
) -> dict:
    """Build a recording dict. ``*_lost`` are frame-index ranges where the hand is untracked."""
    frames = []
    for i in range(frame_count):
        t = round(i / rate_hz, 6)
        sample_time = round(1000.0 + t, 6)
        left_tracked = not (left_lost and i in left_lost)
        right_tracked = not (right_lost and i in right_lost)
        frames.append(
            {
                "t": t,
                "unity_frame": 5000 + i,
                "head": {"position": [0.0, 1.6, 0.0], "rotation": [0.0, 0.0, 0.0, 1.0]},
                "left": hand(left_tracked, t, -0.15, sample_time),
                "right": hand(right_tracked, t, 0.15, sample_time),
            }
        )
    return {
        "schema": SCHEMA_ID,
        "schema_version": SCHEMA_VERSION,
        "recording_id": "synthetic-0001",
        "created_at_utc": "2026-11-03T00:00:00.000Z",
        "participant_id": "synthetic",
        "expression_id": None,
        "notes": "Synthetic fixture generated by tests/factory.py. Not real tracking data.",
        "producer": {
            "app": "suolingo-test-factory",
            "app_version": "0.1.0",
            "unity_version": "n/a",
            "platform": "synthetic",
            "device_model": "synthetic",
        },
        "tracking_source": {
            "provider": "synthetic",
            "sdk_wrapper_version": "n/a",
            "runtime_version": "n/a",
            "joint_layout": "openxr-ext-hand-tracking-26",
            "tracking_origin": "Stage",
        },
        "coordinate_system": {
            "space": "synthetic tracking space",
            "handedness": "left-handed",
            "units": "meters",
            "axes": "+x right, +y up, +z forward",
            "rotation_format": "quaternion-xyzw",
        },
        "capture": {
            "countdown_seconds": 3.0,
            "requested_duration_seconds": round((frame_count - 1) / rate_hz, 6),
            "start_realtime_seconds": 100.0,
            "display_refresh_rate_hz": rate_hz,
            "end_reason": "completed",
            "time_base": "t = Unity realtimeSinceStartup at sampling minus start_realtime_seconds",
        },
        "joints": list(JOINT_NAMES),
        "fingers": list(FINGER_NAMES),
        "frames": frames,
        "summary": None,
    }


if __name__ == "__main__":
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(json.dumps(make_recording(), separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"Wrote {FIXTURE_PATH}")
